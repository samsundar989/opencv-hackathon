"""Episode set v5 (D-0014 king tides + RECALIBRATE, D-0015 W5) — rules-arm results -> results/agent_eval/V5_TIDE_RECAL.md.

Reads the final rules run on v5 (results/agent_eval/runs/rules.jsonl) and the archived v4 rules run
(runs_v1/rules_v4_final.jsonl). Numbers in the markdown come only from these two files.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "agent_eval"
PRED = re.compile(r"predicted high tide next 24 h ([\d.]+) ft")


def load(p: Path) -> pd.DataFrame:
    d = pd.DataFrame([json.loads(ln) for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()])
    return d[d["kind"] != "fleet"]


def pred_high(r) -> float | None:
    s = " ".join(st["result_summary"] for st in r["decision"]["steps"] if st["tool"] == "get_gauge")
    m = PRED.search(s)
    return float(m.group(1)) if m else None


def main():
    new, old = load(RES / "runs" / "rules.jsonl"), load(RES / "runs_v1" / "rules_v4_final.jsonl")
    eps = {e["episode_id"]: e for e in (json.loads(ln) for ln in (RES / "episodes.jsonl").read_text(encoding="utf-8").splitlines() if ln.strip())}
    v4 = new[new["episode_id"].isin(old["episode_id"])]
    v5 = new[~new["episode_id"].isin(old["episode_id"])]
    m = old.merge(new, on=["episode_id", "rep"], suffixes=("_v4", "_v5"))
    changed = m[m["actions_v4"] != m["actions_v5"]].drop_duplicates("episode_id")
    tidal = new[(new["rep"] == 0) & new["kind"].str.startswith(("tidal_tide", "king_tide_control"))]
    false_adv = tidal[tidal["actions"].str.contains("TIDE_ADVISORY")]
    L = ["# Agent episode set v5: king-tide advisory and RECALIBRATE (rules arm)", "",
         "Generated by `scripts/agent_v5_summary.py` from `runs/rules.jsonl` (final rules run on v5, 3 repeats, no Bedrock) "
         "and `runs_v1/rules_v4_final.jsonl`. Expected actions were committed before the run (`0e5cd00`); freeze `FROZEN.json`.", "",
         f"- Rules arm on v5: task success **{new['success'].mean():.1%}** over {len(new)} runs ({new['episode_id'].nunique()} single-site episodes x 3).",
         f"- The 120 v4 episodes: **{v4['success'].mean():.2%}** (v4 run: {old['success'].mean():.2%}); "
         f"{len(changed)} episode(s) changed actions, listed below.", "",
         "| v5 kind | source | runs | success |", "|---|---|---|---|"]
    for k, g in v5.groupby("kind"):
        L.append(f"| {k} | {g['source'].iloc[0]} | {len(g)} | {g['success'].mean():.0%} |")
    L += ["", "## King tides: the pre-registered rule does not work at Savannah", "",
          "Rule: draft TIDE_ADVISORY when the harmonic prediction (M2, S2, K1, O1 + trend, fit on 15 days ending 6 h before "
          "the frame) for the next 24 h reaches the site's daily-max p99.", "",
          "| episode | label | predicted next-24 h high (ft) | site daily-max p99 (ft) | decision |", "|---|---|---|---|---|"]
    p99 = {"GA_Savannah_River_at_USACE_Dock_at_Savannah": 5.824, "CA_First_Mallard_Branch_nr_Fairfield": 29.762}
    tid = json.loads((ROOT / "src" / "riversight" / "agent" / "tidal_sites.json").read_text(encoding="utf-8"))
    for _, r in new[(new["rep"] == 0) & new["kind"].isin(["king_tide", "king_tide_control", "tidal_tide"])].sort_values("episode_id").iterrows():
        ph = pred_high(r)
        L.append(f"| {r['episode_id']} | {r['kind']} | {ph if ph is not None else '–'} | "
                 f"{tid.get(r['cam_id'], {}).get('daily_max_p99', p99.get(r['cam_id']))} | {r['actions']} |")
    kt = v5[v5["kind"] == "king_tide"]
    L += ["", f"- Real king tides caught: **{int(kt[kt['rep'] == 0]['success'].sum())}/{kt['episode_id'].nunique()}** "
              "(Savannah; frames ~12 h before an observed daily-max-p99 high water). The forecast times the high water well "
              "but predicts it 0.2–0.7 ft too low: Savannah's p99 days include a non-astronomical part (river flow, wind) "
              "that four constituents cannot predict.",
          f"- Ordinary-tide frames with an advisory anyway: **{len(false_adv)}/{len(tidal)}** "
          + (f"({', '.join(false_adv['episode_id'])})" if len(false_adv) else "") + ".",
          "- First Mallard had no daily-max-p99 day with a daylight frame 6–24 h before, so it contributes controls only.",
          "- This is the pre-registered result and is reported as is. A better forecast (more constituents, a longer fit, "
          "NOAA predictions where a station exists) would be a post-hoc change with only 4 events to test it on.", "",
          "## RECALIBRATE", "",
          f"- All five synthetic variants pass ({v5[v5['kind'].str.startswith('recal_')]['success'].mean():.0%} of "
          f"{int(v5['kind'].str.startswith('recal_').sum())} runs). It fires on W4's drift signal or a flood-extended range "
          "with a refit built on the served model, and stays silent with no refit, a refit built on another model, or no drift.",
          "- The evidence is synthetic (W4's fixtures on real frames); the live drift files appear only once W4's cycle "
          "wiring is deployed.", "",
          "## v4 episodes whose actions changed", ""]
    for _, r in changed.iterrows():
        L.append(f"- `{r['episode_id']}`: {r['actions_v4']} -> {r['actions_v5']} "
                 f"(success {r['success_v4']} -> {r['success_v5']}; {eps.get(r['episode_id'], {}).get('note', '')[:120]})")
    (RES / "V5_TIDE_RECAL.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
